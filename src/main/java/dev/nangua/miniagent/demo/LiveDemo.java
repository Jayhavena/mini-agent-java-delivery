package dev.nangua.miniagent.demo;

import dev.nangua.miniagent.agent.AgentConfig;
import dev.nangua.miniagent.agent.AgentFactory;
import dev.nangua.miniagent.agent.AgentReply;
import dev.nangua.miniagent.llm.LlmConfig;
import dev.nangua.miniagent.session.Session;
import dev.nangua.miniagent.util.Json;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.OffsetDateTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.List;

/**
 * Reproducible live-API scenario for the README:
 * one user, two independent windows, tool calls, follow-ups and todo isolation.
 *
 * <p>可复现的真机演示：同一用户开两个独立窗口交替对话，验证工具调用、同窗口
 * 追问召回，以及 todo 状态按窗口隔离。模型调用是真实的，天气/搜索类工具是
 * mock；跑完把逐 turn 问答、工具轨迹与两个窗口的 toolState 写入 Markdown
 * 证据文件，供 README 引用。这是人工检查用的演示记录，不是覆盖全部场景的断言式验收。
 */
public final class LiveDemo {
    private static final String USER = "alice";

    public static void main(String[] args) throws Exception {
        Path dataDir = Path.of("data/live-demo");
        Path out = Path.of("data/live-demo-output.md");
        for (int i = 0; i < args.length; i++) {
            if ("--data-dir".equals(args[i]) && i + 1 < args.length) {
                dataDir = Path.of(args[++i]);
            } else if ("--out".equals(args[i]) && i + 1 < args.length) {
                out = Path.of(args[++i]);
            }
        }

        LlmConfig llmConfig = LlmConfig.fromEnvironment();
        if (!llmConfig.hasApiKey()) {
            System.err.println("Set LLM_API_KEY or DEEPSEEK_API_KEY before running the live demo.");
            System.exit(2);
        }
        AgentFactory.Wired wired = AgentFactory.create(dataDir, llmConfig, AgentConfig.defaults());

        Session window1 = wired.sessions().create(USER, "窗口1-天气与待办");
        Session window2 = wired.sessions().create(USER, "窗口2-周报与待办");

        List<Turn> turns = new ArrayList<>();
        // 刻意交替在两个窗口提问：窗口 1 记的待办、查的天气，正好被后面的
        // 追问（同窗口召回）和窗口 2 的提问（跨窗口隔离）当考题。
        turns.add(turn(wired, window1,
                "帮我查一下杭州现在的天气，然后在待办里加一条“明天带伞”。"));
        turns.add(turn(wired, window2,
                "参考 docs/agent-notes.md 的项目说明，写一段本周工作周报："
                        + "完成工具调用与会话隔离联调、修复 3 个 bug、下周做上下文性能优化；"
                        + "然后把“周五 18:00 前发周报”记到这个窗口的待办。"));
        turns.add(turn(wired, window1,
                "我刚才让你记的待办是什么？顺便说一下刚才杭州的天气。"));
        turns.add(turn(wired, window2,
                "列一下这个窗口的待办，不要列别的窗口的。"));
        turns.add(turn(wired, window1,
                "那再帮我算一下 (23 + 7) * 3 / 5 等于多少？"));

        StringBuilder md = new StringBuilder();
        md.append("# Live DeepSeek run\n\n");
        md.append("- Generated: ").append(OffsetDateTime.now()
                .format(DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH:mm:ssxxx"))).append("\n");
        md.append("- Model: `").append(llmConfig.model()).append("`\n");
        md.append("- Endpoint: `").append(llmConfig.baseUrl()).append("`\n");
        md.append("- User: `").append(USER).append("`\n");
        md.append("- Data dir: `").append(repositoryRelativePath(dataDir)).append("`\n\n");
        md.append("> This file is generated by `dev.nangua.miniagent.demo.LiveDemo` against the real API. ")
                .append("Weather/search data are mock tools; the model calls are real. ")
                .append("This is a demonstration for manual inspection, not an assertion-based acceptance suite.\n\n");

        for (Turn turn : turns) {
            md.append("## ").append(turn.session().getTitle()).append("\n\n");
            md.append("**User:** ").append(turn.input()).append("\n\n");
            md.append("**Agent:** ").append(turn.reply().answer()).append("\n\n");
            if (!turn.reply().toolCalls().isEmpty()) {
                md.append("**Tool trace:**\n\n");
                for (AgentReply.ToolCallRecord call : turn.reply().toolCalls()) {
                    md.append("- `").append(call.name()).append("` ")
                            .append(call.ok() ? "ok" : "failed")
                            .append(" (").append(call.durationMs()).append(" ms), args=`")
                            .append(Json.preview(Json.write(call.arguments()), 240))
                            .append("`, result=`")
                            .append(Json.preview(call.resultPreview(), 260)).append("`\n");
                }
                md.append("\n");
            }
            md.append("_steps=").append(turn.reply().steps())
                    .append(", stop=").append(turn.reply().stopReason())
                    .append(", ctx_tokens~").append(turn.reply().estimatedContextTokens())
                    .append("_\n\n");
        }

        md.append("## Persisted todo state (isolation check)\n\n");
        md.append("### ").append(window1.getTitle()).append(" (`").append(window1.getId()).append("`)\n\n");
        md.append("```json\n").append(Json.pretty(window1.getToolState())).append("\n```\n\n");
        md.append("### ").append(window2.getTitle()).append(" (`").append(window2.getId()).append("`)\n\n");
        md.append("```json\n").append(Json.pretty(window2.getToolState())).append("\n```\n");

        Path parent = out.toAbsolutePath().normalize().getParent();
        if (parent != null) {
            Files.createDirectories(parent);
        }
        Files.writeString(out, md.toString(), StandardCharsets.UTF_8);
        System.out.println("\nLive demo complete. Evidence written to: " + repositoryRelativePath(out));
    }

    /** Render portable paths only; unknown or external locations must not expose local directories. */
    private static String repositoryRelativePath(Path path) {
        Path repositoryRoot = Path.of("").toAbsolutePath().normalize();
        while (repositoryRoot != null
                && !(Files.isRegularFile(repositoryRoot.resolve("pom.xml"))
                && Files.isDirectory(repositoryRoot.resolve("src/main/java/dev/nangua/miniagent")))) {
            repositoryRoot = repositoryRoot.getParent();
        }
        Path absolute = path.toAbsolutePath().normalize();
        if (repositoryRoot == null || !absolute.startsWith(repositoryRoot)) {
            return "[outside-repository]";
        }
        String relative = repositoryRoot.relativize(absolute).toString().replace('\\', '/');
        return relative.isEmpty() ? "." : relative;
    }

    private static Turn turn(AgentFactory.Wired wired, Session session, String input) {
        System.out.println("\n============================================================");
        System.out.println("[" + session.getTitle() + "] " + session.getId());
        System.out.println("User> " + input);
        AgentReply reply = wired.runtime().chat(session, input);
        for (AgentReply.ToolCallRecord call : reply.toolCalls()) {
            System.out.printf("  [tool] %s %s (%d ms) args=%s%n", call.name(),
                    call.ok() ? "ok" : "failed", call.durationMs(),
                    Json.preview(Json.write(call.arguments()), 200));
            System.out.println("         -> " + Json.preview(call.resultPreview(), 220));
        }
        System.out.println("Agent> " + reply.answer());
        System.out.printf("  [stats] steps=%d tools=%d stop=%s ctx~%d%n",
                reply.steps(), reply.toolCalls().size(), reply.stopReason(),
                reply.estimatedContextTokens());
        return new Turn(session, input, reply);
    }

    private record Turn(Session session, String input, AgentReply reply) {
    }
}
